objects="$objects $stage/objects/12.o"
cc -D_GNU_SOURCE -D__wasm__ -Iinclude/wasm-posix-libuv -Iinclude -Isrc -Isrc/unix -c src/unix/core.c -o "$stage/objects/13.o"
objects="$objects $stage/objects/13.o"
