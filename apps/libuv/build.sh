cc -D_GNU_SOURCE -D__wasm__ -Iinclude/wasm-posix-libuv -Iinclude -Isrc -Isrc/unix -c src/fs-poll.c -o "$stage/objects/0.o"
objects="$objects $stage/objects/0.o"
