#!/bin/sh
set -eu
tar -xf source.tar
stage="$PWD/stage"
cd source
mkdir -p "$stage/objects" "$stage/include" "$stage/pkgconfig"
objects=
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c png.c -o "$stage/objects/0.o"
objects="$objects $stage/objects/0.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngerror.c -o "$stage/objects/1.o"
objects="$objects $stage/objects/1.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngget.c -o "$stage/objects/2.o"
objects="$objects $stage/objects/2.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngmem.c -o "$stage/objects/3.o"
objects="$objects $stage/objects/3.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngpread.c -o "$stage/objects/4.o"
objects="$objects $stage/objects/4.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngread.c -o "$stage/objects/5.o"
objects="$objects $stage/objects/5.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngrio.c -o "$stage/objects/6.o"
objects="$objects $stage/objects/6.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngrtran.c -o "$stage/objects/7.o"
objects="$objects $stage/objects/7.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngrutil.c -o "$stage/objects/8.o"
objects="$objects $stage/objects/8.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngset.c -o "$stage/objects/9.o"
objects="$objects $stage/objects/9.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngtrans.c -o "$stage/objects/10.o"
objects="$objects $stage/objects/10.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngwio.c -o "$stage/objects/11.o"
objects="$objects $stage/objects/11.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngwrite.c -o "$stage/objects/12.o"
objects="$objects $stage/objects/12.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngwtran.c -o "$stage/objects/13.o"
objects="$objects $stage/objects/13.o"
cc -DPNG_NO_REQUIRE_SOURCES -DZLIB_NO_REQUIRE_SOURCES -I. -I/usr/local/include -c pngwutil.c -o "$stage/objects/14.o"
objects="$objects $stage/objects/14.o"
ar rcs "$stage/libpng16.a" $objects
cc -shared $objects -lz -Wl,-soname,libpng16.so -o "$stage/libpng16.so"
sed '/^__require_source(/d' png.h > "$stage/include/png.h"
sed '/^__require_source(/d' pngconf.h > "$stage/include/pngconf.h"
sed '/^__require_source(/d' pnglibconf.h > "$stage/include/pnglibconf.h"
cp port/libpng.pc "$stage/pkgconfig/"

mkdir -p "$DESTDIR/lib/pkgconfig" "$DESTDIR/include" "$DESTDIR/share/licenses/libpng"
cp "$stage/"*.a "$stage/"*.so "$DESTDIR/lib/"
cp -R "$stage/include/." "$DESTDIR/include/"
cp "$stage/pkgconfig/"*.pc "$DESTDIR/lib/pkgconfig/"
cp "LICENSE" "$DESTDIR/share/licenses/libpng/LICENSE"
